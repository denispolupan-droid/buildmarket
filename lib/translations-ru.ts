// ── Ukrainian measurement units → Russian ────────────────────────────────────
// Uses Cyrillic lookahead/lookbehind because JS \b doesn't match Unicode.
// ORDER MATTERS: год→ч (hours) must run before рік→год (years) to avoid
// the newly-created "год" being re-converted. Each regex runs exactly once.
const _C = '[а-яА-ЯіїєёІЇЄ]';
const UNIT_RU: [RegExp, string][] = [
  [new RegExp(`(?<!${_C})год(?!${_C})`,    'g'), 'ч'],      // годин(а) abbr → ч
  [new RegExp(`(?<!${_C})годин(?!${_C})`,  'g'), 'ч'],      // годин → ч
  [new RegExp(`(?<!${_C})годину(?!${_C})`, 'g'), 'ч'],      // годину → ч
  [new RegExp(`(?<!${_C})хв(?!${_C})`,     'g'), 'мин'],    // хвилин abbr → мин
  [new RegExp(`(?<!${_C})хвилин(?!${_C})`, 'g'), 'мин'],    // хвилин → мин
  [new RegExp(`(?<!${_C})років(?!${_C})`,  'g'), 'лет'],    // 5+ years
  [new RegExp(`(?<!${_C})роки(?!${_C})`,   'g'), 'года'],   // 2-4 years
  [new RegExp(`(?<!${_C})рік(?!${_C})`,    'g'), 'год'],    // 1 year (after год→ч!)
  [new RegExp(`(?<!${_C})доби(?!${_C})`,   'g'), 'суток'],  // 2-4 days
  [new RegExp(`(?<!${_C})доба(?!${_C})`,   'g'), 'сутки'],  // 1 day
  [new RegExp(`(?<!${_C})діб(?!${_C})`,    'g'), 'суток'],  // 5+ days
];

