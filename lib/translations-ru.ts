export function tFilterLabel(label: string, lang: 'uk' | 'ru'): string {
  if (lang !== 'ru') return label;
  return FILTER_LABELS_RU[label] ?? label;
}

export function tFilterValue(value: string, lang: 'uk' | 'ru'): string {
  if (lang !== 'ru') return value;
  const exact = FILTER_VALUES_RU[value];
  if (exact) return exact;
  // Handle "/" separator (e.g. "Рожевий / безбарвний")
  if (value.includes('/')) {
    return value.split('/').map(p => tFilterValue(p.trim(), lang)).join(' / ');
  }
  // Word-level substitution fallback
  let result = value;
  for (const [ua, ru] of WORD_SUBS) {
    if (result.includes(ua)) result = result.split(ua).join(ru);
  }
  // Measurement unit replacement (regex, Cyrillic-boundary safe)
  for (const [re, ru] of UNIT_RU) {
    result = result.replace(re, ru);
  }
  return result;
}
