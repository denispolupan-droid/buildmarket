/**
 * Пошук людей за ім'ям, коли українське й російське написання різні.
 *
 * Покупець у базі записаний так, як прийшов із площадки: «Стельмах Александр»
 * з Rozetka, «Олександр Стельмах» із сайту. Менеджер шукає як звик — і не
 * знаходить. Різниця буває двох видів, і лікуються вони по-різному.
 *
 * 1. ОРФОГРАФІЯ (і/и/ы, є/е/э/ё, ґ/г, апостроф, м'який знак) — «Лисенко» проти
 *    «Лысенко», «Сергієнко» проти «Сергиенко». Таких прізвищ тисячі, списком їх
 *    не перебрати, тому обидві сторони зводяться до одного вигляду — fold().
 *    Те саме правило стоїть у generated-колонках orders.contact_norm /
 *    company_norm (міграція 134): міняти його тут можна тільки разом із ними.
 *
 * 2. РІЗНІ КОРЕНІ — «Олександр» проти «Александр», «Микола» проти «Николай».
 *    Буквами не звести, тут потрібен список NAME_STEMS. Він працює по КОРЕНЮ, а
 *    не по цілому слову, тож по батькові («Олексійович» / «Алексеевич») і
 *    пестливі форми підтягуються самі, без окремих рядків.
 */

/** Звести написання до спільного вигляду: і/ї/ы → и, є/е/э/ё → е, ґ → г, зняти ' ’ - ь ъ. */
export function fold(s: string): string {
  const map: Record<string, string> = { 'і': 'и', 'ї': 'и', 'ы': 'и', 'ё': 'е', 'э': 'е', 'є': 'е', 'ґ': 'г' };
  const drop = new Set(["'", '’', 'ʼ', '`', '-', 'ь', 'ъ']);
  let out = '';
  for (const ch of s.toLowerCase()) {
    if (drop.has(ch)) continue;
    out += map[ch] ?? ch;
  }
  return out;
}

/**
 * Корені імен, які орфографією не зводяться. Кожна група — те саме ім'я в
 * різних написаннях; шукаємо за всіма коренями групи одразу.
 *
 * Корені записані вже згорнутими (після fold). Група з одного кореня — це не
 * помилка, а обрізання до спільної частини: «Дмитро» і «Дмитрий» різняться лише
 * закінченням, корінь «дмитр» покриває обидва. Там, де одне написання є
 * підрядком іншого («анна» в «ганна», «катерина» в «екатерина»), запису теж не
 * треба — підрядковий пошук знайде сам.
 *
 * Список свідомо короткий: сюди йдуть лише імена, що реально трапляються в
 * замовленнях. Доповнювати — рядком у цей масив, міграція не потрібна.
 */
export const NAME_STEMS: readonly (readonly string[])[] = [
  ['олександр', 'александр'],
  ['олекси', 'алексе'],
  ['олена', 'елена'],
  ['микола', 'никола'],
  ['дмитр'],
  ['серги', 'серге'],
  ['андри', 'андре'],
  ['петр'],
  ['павл', 'павел'],
  ['михайл', 'михаил'],
  ['володимир', 'владимир'],
  ['натал'],
  ['васил'],
  ['тетян', 'татян'],
  ['свитлан', 'светлан'],
  ['евген'],
  ['федир', 'федор'],
  ['нади', 'надежд'],
  ['вира', 'вера'],
  ['пилип', 'филипп'],
  ['мария', 'маря'],
  ['степан', 'стефан'],
  ['юри'],
  ['григори'],
];

/**
 * Закінчення, після яких корінь лишається ІМЕНЕМ: сама форма імені, жіночий
 * рід і по батькові. Прізвища, утворені від імені, сюди не входять — і це
 * головне: без цієї перевірки «Сергієнко» («серги» + «енко») шукало б усіх
 * Сергіїв, а «Петренко» — усіх Петрів, замість конкретного прізвища.
 */
const NAME_SUFFIXES = new Set([
  '', 'а', 'о', 'е', 'й', 'я', 'и', 'ий', 'ей', 'ия',
  'ович', 'овича', 'овичу', 'овна', 'ивна', 'евич', 'евича', 'евна',
  'йович', 'йовича', 'ична',
]);

/**
 * Фрагменти для пошуку одного слова запиту: або корені його групи (якщо слово
 * справді ім'я чи по батькові з цим коренем), або саме слово, згорнуте fold().
 * Шукати треба за будь-яким із них (АБО).
 */
export function nameFragments(word: string): string[] {
  const w = fold(word);
  if (!w) return [];
  const group = NAME_STEMS.find(stems =>
    stems.some(stem => w.startsWith(stem) && NAME_SUFFIXES.has(w.slice(stem.length))));
  return group ? [...group] : [w];
}
