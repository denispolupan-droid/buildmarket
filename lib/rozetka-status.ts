/**
 * Становище у воронці. Порівнювати статуси напряму не можна: у Rozetka своя
 * драбина ідентифікаторів, у нас своя назва станів, спільного порядку немає.
 * Зводимо обидві до однієї шкали «наскільки далеко просунулось замовлення».
 */
const ROZETKA_STAGE: Record<number, number> = {
  1: 0,                         // ще не бралися
  26: 1, 2: 1,                  // взяли в роботу
  61: 2, 3: 2, 4: 2, 5: 2,      // передали перевізникові / везуть
  // Проміжні статуси доставки в точки видачі. Без них шкала мовчала: у замовленні
  // 26081007 Rozetka вже прийняла посилку (81), а плашка «в кабінеті» не зʼявлялася,
  // бо ROZETKA_STAGE[81] було undefined — і isRozetkaAhead чесно повертав false.
  // Заодно драбина пушів перестає бити 61 у замовлення, яке вже поїхало.
  80: 2, 81: 2, 82: 2,
  6: 3,                         // виконано
};

const OUR_STAGE: Record<string, number> = {
  new: 0, pending_payment: 0,
  confirmed: 1, awaiting_stock: 1, picking: 1,
  shipped: 2,
  delivered: 3,
};

/**
 * Кабінет попереду нас — тобто там замовлення вже рухнули, а в нас воно висить
 * необробленим. Саме це й треба підсвітити менеджеру.
 *
 * Скасування (група 3) сюди не входять навмисно: у них немає місця у воронці, і
 * ними займаються окремі сторожі — watchRozetkaCancellations / watchRozetkaRefunds.
 */
/**
 * Крок веде назад по воронці Rozetka? Потрібно драбині проміжних статусів:
 * «лікувати» відмову переходу можна лише кроком уперед, інакше замовлення
 * відкочується в кабінеті на попередню стадію, і покупець бачить, що воно
 * повернулося в обробку.
 *
 * Невідомий поточний статус — не заважаємо: повертаємо false, драбина працює
 * як раніше.
 */
export function isRozetkaBackwards(step: number, currentStatus: number | null | undefined): boolean {
  if (currentStatus == null) return false;
  const from = ROZETKA_STAGE[currentStatus];
  const to = ROZETKA_STAGE[step];
  if (from === undefined || to === undefined) return false;
  return to <= from;
}

/**
 * Rozetka не випустить замовлення з «в обробці» без номера накладної.
 * Перевірено живими PUT по замовленню 904417517 (31.08.2026): 3 «Передано до
 * служби доставки» відповідає `ttn: Необхідно заповнити Номер ТТН`, 5 «Очікує
 * в пункті самовивозу» — «Перехід в цей статус неможливий», а 6 «Виконано»
 * недосяжне напряму й іде драбиною через 61, якому ТТН теж потрібен.
 *
 * Наслідок: замовлення, відвантажене без накладної (самовивіз, передача з рук
 * у руки), у кабінеті застрягає назавжди, а крон щоп'ять хвилин мовчки б'ється
 * об ту саму відмову. Підставити номер за людину ми не можемо — його треба
 * внести в замовлення, тож єдина корисна дія тут — сказати про це вголос.
 *
 * Коли перевізникові вже передали (стадія 2 і далі), номер у кабінеті вже є —
 * тоді 6 доїжджає без нової накладної, і блокування не діє.
 */
const NEEDS_TTN = new Set([3, 6, 61]);

export function rozetkaNeedsTtn(
  desired: number,
  currentStatus: number | null | undefined,
  hasTtn: boolean,
): boolean {
  if (hasTtn || !NEEDS_TTN.has(desired)) return false;
  return (currentStatus == null ? 0 : ROZETKA_STAGE[currentStatus] ?? 0) < 2;
}

export function isRozetkaAhead(rozetkaStatus: number | null | undefined, ourStatus: string): boolean {
  if (rozetkaStatus == null) return false;
  const rz = ROZETKA_STAGE[rozetkaStatus];
  const ours = OUR_STAGE[ourStatus];
  if (rz === undefined || ours === undefined) return false;
  return rz > ours;
}
