/**
 * Статуси кабінету Rozetka — тільки для показу. Чистий модуль без мережі й без
 * ключів: його імпортує і серверний rozetka-api, і клієнтська адмінка, а в
 * rozetka-api живе сервісний ключ Supabase, тож тягнути його в браузер не можна.
 *
 * Навіщо взагалі показувати статус кабінету окремо. Наш статус і статус Rozetka
 * живуть незалежно: наше «Підтверджено» — не мітка, а складська операція
 * (резерв товару / замовлення постачальнику), і режим виконання обирає людина.
 * Тому статус із кабінету не підтягується в наш автоматично — менеджер бачить
 * плашку «в кабінеті вже прийнято» і натискає «Підтвердити» сам.
 */

