/**
 * Запобіжники перед відвантаженням.
 *
 * Живий кейс 01.09.2026 (#26091002): замовлення створене в адмінці з доставкою
 * за замовчуванням «Самовивіз», до нього прив'язали ЕН Нової Пошти сусіднього
 * замовлення (одна посилка на два замовлення) і натиснули «Відвантажити».
 * Для самовивозу відвантаження = передано клієнту в руки, тож система одразу
 * провела РН з виручкою/собівартістю і поставила «Доставлено» — постачальник
 * ще навіть не бачив замовлення. Відкат — тільки сторно через скасування.
 * Тому: самовивіз із номером накладної перевізника — майже напевно не той тип
 * доставки, і відвантажувати не можна, поки людина не виправить картку.
 */

export type ShipGuardOrder = {
  delivery_type?: string | null;
  tracking_number?: string | null;
  tracking_ref?: string | null;
};

/** Текст помилки, якщо відвантажувати не можна; null — можна. */
export function pickupWithTtnError(order: ShipGuardOrder, bodyTtn?: string | null): string | null {
  if (order.delivery_type !== 'pickup') return null;
  const ttn = (bodyTtn ?? '').trim() || (order.tracking_number ?? '').trim();
  const hasCarrierLink = ttn.length > 0 || Boolean((order.tracking_ref ?? '').trim());
  if (!hasCarrierLink) return null;
  return `Доставка в замовленні — «Самовивіз», але до нього прив'язана накладна перевізника${ttn ? ` №${ttn}` : ''}. `
    + 'Відвантаження самовивозу одразу проводить продаж як доставлений. '
    + 'Якщо посилка їде перевізником — змініть тип доставки в блоці «Доставка» і відвантажте знову; '
    + 'якщо клієнт справді забирає сам — приберіть накладну.';
}
