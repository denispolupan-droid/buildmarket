// Розбір грошової суми, введеної людиною.
//
// Голий parseFloat('52 077,80') дає 52: він зупиняється на пробілі-роздільнику
// тисяч. А саме в такому вигляді сума потрапляє в поле — її копіюють із
// підсумкового рядка на екрані, де числа відформатовані під українську локаль
// (нерозривні пробіли між тисячами, кома перед копійками). Наслідок був тихий і
// дорогий: у полі «52 077,80», в оплаті — 52 ₴.
//
// Правила: прибираємо будь-які пробіли й апострофи-роздільники, а роздільником
// дробової частини вважаємо ОСТАННЮ кому чи крапку — усе, що перед нею, ділить
// тисячі. Повертаємо NaN, якщо числа немає: викликач сам вирішує, чи це нуль.
export function parseMoney(value: unknown): number {
  let s = String(value ?? '').replace(/[\s'’]/g, '');
  const last = Math.max(s.lastIndexOf(','), s.lastIndexOf('.'));
  if (last >= 0) {
    s = s.slice(0, last).replace(/[.,]/g, '') + '.' + s.slice(last + 1);
  }
  const n = parseFloat(s);
  return Number.isFinite(n) ? n : NaN;
}
