/** Побудова мапи normKey(аліас|канон) → канонічний label. */
export function buildAliasMap() {
  const map = new Map();
  for (const d of DICTIONARY) {
    map.set(normKey(d.label), d.label);
    for (const a of d.aliases) {
      const k = normKey(a);
      if (map.has(k) && map.get(k) !== d.label) {
        throw new Error(`Аліас "${a}" конфліктує: ${map.get(k)} vs ${d.label}`);
      }
      map.set(k, d.label);
    }
  }
  return map;
}

/** Канонічний лейбл для довільного лейбла з даних (з урахуванням спец-правил). */
export function canonicalLabel(label, value, aliasMap) {
  const byValue = valueBasedLabel(label, value);
  if (byValue) return byValue;
  return aliasMap.get(normKey(label)) ?? null; // null → лейбл поза словником
}

export function sortIndex(label) {
  const d = DICTIONARY.find(d => d.label === label);
  return d ? d.sort : 850; // невідомі (поза словником) — між "інше" та Брендом
}
