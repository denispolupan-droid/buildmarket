/** Рядки для таблиці characteristic_values / buildValueRules (label у кожному рядку). */
export function charValueRows() {
  const rows = [];
  for (const [label, list] of Object.entries(CHAR_VALUES)) {
    list.forEach((v, i) => rows.push({
      label, value: v.value, category_slugs: v.cats ?? [], aliases: v.aliases ?? [],
      match_patterns: v.match ?? [], sort_order: v.sort ?? (i + 1) * 10,
    }));
  }
  return rows;
}

/**
 * Спец-правила, які вирішують канонічний лейбл ЗА ЗНАЧЕННЯМ (тільки для чистки
 * legacy-даних; AI і форма більше не породжують такі лейбли).
 * Повертає канонічний label або null (правило не застосовується).
 */
export function valueBasedLabel(label, value) {
  const k = normKey(label);
  const v = String(value ?? '').toLowerCase();
  // «Сфера застосування»: внутрішні/зовнішні роботи → Тип використання, інакше — Область застосування
  if (k === 'сфера застосування' || k === 'сфера використання') {
    return /внутрішн|зовнішн|фасад|інтер'єр|интерьер/.test(v) ? 'Тип використання' : 'Область застосування';
  }
  // «Об'єм / Вага»: за одиницею значення
  if (k === "об'єм / вага" || k === "об'єм/вага") {
    return /\d\s*(кг|г)\b/.test(v) ? 'Вага' : "Об'єм";
  }
  return null;
}

