// Нормалізація ключа лейбла для порівняння (та сама, що в lib/characteristics.ts)
export function normKey(s) {
  return String(s ?? '')
    .replace(/['`´ʼ']/g, "'")
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

