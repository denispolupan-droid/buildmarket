// ── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  console.log('\n📚 Застосування словника характеристик');
  if (DRY_RUN) console.log('🔍 DRY RUN — без запису в БД\n');

  // ── Перейменування ярликів ──────────────────────────────────────────────────
  if (!ONLY_LABEL) {
    console.log('\n🏷  Перейменування ярликів:');
    for (const [from, to] of Object.entries(LABEL_RENAMES)) {
      const { data: matches } = await supabase
        .from('product_characteristics')
        .select('id')
        .eq('label', from);
      if (!matches?.length) { console.log(`  ✓ "${from}" — не знайдено`); continue; }
      console.log(`  "${from}" → "${to}"  (${matches.length} записів)`);
      if (!DRY_RUN) {
        await supabase.from('product_characteristics').update({ label: to }).eq('label', from);
      }
    }
  }

  const labels = ONLY_LABEL ? [ONLY_LABEL] : Object.keys(VOCABULARY);
  let totalChanges = 0;

  for (const label of labels) {
    const mapping = VOCABULARY[label];
    if (!mapping) { console.log(`⚠ Словник не знайдено для: ${label}`); continue; }

    const entries = Object.entries(mapping);
    console.log(`\n📝 ${label} — ${entries.length} правил`);

    for (const [from, to] of entries) {
      if (from === to) continue;

      // Count matches
      const { data: matches } = await supabase
        .from('product_characteristics')
        .select('id')
        .eq('label', label)
        .eq('value', from);

      if (!matches?.length) continue;

      console.log(`  "${from}" → "${to}"  (${matches.length} записів)`);
      totalChanges += matches.length;

      if (!DRY_RUN) {
        await supabase
          .from('product_characteristics')
          .update({ value: to })
          .eq('label', label)
          .eq('value', from);
      }
    }
  }

  console.log(`\n📊 Підсумок: ${totalChanges} записів ${DRY_RUN ? 'буде змінено' : 'змінено'}\n`);
  if (DRY_RUN) console.log('   Запустіть без --dry-run щоб застосувати.\n');
}

main().catch(err => { console.error('\n❌', err.message); process.exit(1); });
