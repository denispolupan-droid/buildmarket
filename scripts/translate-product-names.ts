function translateName(name: string): string {
  let result = name;
  for (const [uk, ru] of DICT) {
    if (result.includes(uk)) {
      result = result.split(uk).join(ru);
    }
  }
  return result;
}

async function main() {
  console.log(`\n📦 Translate product names UK → RU ${DRY_RUN ? '[DRY RUN]' : ''}\n`);

  const { data: products, error } = await supabase
    .from('products')
    .select('sku, name')
    .eq('is_active', true)
    .is('name_ru', null)
    .order('sku');

  if (error) { console.error('DB error:', error); process.exit(1); }
  if (!products?.length) { console.log('✅ All products already have name_ru.'); return; }

  console.log(`Found ${products.length} products without name_ru\n`);

  const updates: { sku: string; name: string; name_ru: string }[] = [];

  for (const p of products) {
    const name_ru = translateName(p.name);
    updates.push({ sku: p.sku, name: p.name, name_ru });
  }

  // Preview first 30
  console.log('Preview (first 30):');
  for (const u of updates.slice(0, 30)) {
    const changed = u.name !== u.name_ru;
    const flag = changed ? '✓' : '~';
    console.log(`${flag} ${u.sku}: ${u.name_ru}`);
    if (!changed) console.log(`  ⚠ UNCHANGED: ${u.name}`);
  }
  console.log();

  const unchanged = updates.filter(u => u.name === u.name_ru);
  console.log(`Total: ${updates.length} | Changed: ${updates.length - unchanged.length} | Unchanged: ${unchanged.length}`);

  if (SHOW_UNCHANGED || unchanged.length <= 30) {
    console.log('\nUnchanged products (names already identical in Russian):');
    for (const u of unchanged) console.log(`  ${u.sku}: ${u.name}`);
  }

  if (DRY_RUN) {
    console.log('\n[DRY RUN] No changes written. Remove --dry-run to apply.');
    return;
  }

  const BATCH = 50;
  let done = 0;
  for (let i = 0; i < updates.length; i += BATCH) {
    const batch = updates.slice(i, i + BATCH);
    for (const u of batch) {
      const { error: upErr } = await supabase
        .from('products')
        .update({ name_ru: u.name_ru })
        .eq('sku', u.sku);
      if (upErr) console.error(`  ✗ ${u.sku}: ${upErr.message}`);
      else done++;
    }
    process.stdout.write(`Updated ${Math.min(i + BATCH, updates.length)}/${updates.length}...\r`);
  }

  console.log(`\n✅ Done: ${done} products updated.`);
}

main().catch(console.error);
