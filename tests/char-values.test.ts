import { describe, it, expect } from 'vitest';
import { canonicalCharValue, USE_BOTH, USE_IN, USE_OUT } from '../lib/char-values';

// «Тип використання»: 11 формулювань → 3 значення, незалежно від категорії.
describe('Тип використання', () => {
  const t = (v: string) => canonicalCharValue('Тип використання', v);
  it('внутрішні + зовнішні в будь-якому порядку і «універсальний» → обидва', () => {
    for (const v of [
      'Для внутрішніх і зовнішніх робіт', 'Внутрішні роботи, Зовнішні роботи', 'Всередині та зовні приміщень',
      'Зовнішнє та внутрішнє використання', 'Універсальний', 'Металеві та пластикові різьби, внутрішні та зовнішні роботи',
    ]) expect(t(v)).toBe(USE_BOTH);
  });
  it('лише зовнішні / лише внутрішні', () => {
    expect(t('Для зовнішніх робіт')).toBe(USE_OUT);
    expect(t('Зовнішні фасадні роботи')).toBe(USE_OUT);
    expect(t('Внутрішні роботи')).toBe(USE_IN);
    expect(t('Стіни та стелі у внутрішніх приміщеннях')).toBe(USE_IN);
  });
  it('канонічне значення не змінюється', () => {
    expect(t(USE_BOTH)).toBe(USE_BOTH);
  });
});

// «Призначення»: те саме слово в різних категоріях — різний сенс.
describe('Призначення', () => {
  const p = (v: string, cat?: string | null) => canonicalCharValue('Призначення', v, cat);
  it('«метал» у фарбах — антикорозійне фарбування, у дисках і шліфуванні — без змін', () => {
    expect(p('Захист металу від корозії', 'moltkovi-farby')).toBe('Антикорозійний захист та декоративне фарбування металу');
    expect(p('Різання металу', 'vidrizni-dysky')).toBe('Різання металу');
    expect(p('Шліфування металу', 'shlifuvalny')).toBe('Шліфування металу');
  });
  it('без категорії правила категорії не спрацьовують', () => {
    expect(p('Захист металу від корозії')).toBe('Захист металу від корозії');
    expect(p('Захист металу від корозії', null)).toBe('Захист металу від корозії');
  });
  it('ґрунтовки: підготовка/зміцнення → одне значення, цвіль — окремо', () => {
    expect(p('Підготовка поверхонь, Зміцнення поверхонь', 'gruntivky-kontsentraty')).toBe('Ґрунтування та зміцнення поверхонь');
    expect(p('Знищення цвілі, грибка, бактерій та зміцнення поверхні', 'gruntivky-gotovi')).toBe('Захист від цвілі та грибка');
    expect(p('Видалення висолів', 'gruntivky-gotovi')).toBe('Видалення висолів');
  });
  it('лаки: камінь, інтер\'єр, дерево — і порядок правил', () => {
    expect(p('Захист та декорування каменю, бетон, Цегла, мінеральних поверхонь (фасад та інтер\'єр)', 'laky')).toBe('Захист та декорування каменю, бетону та цегли');
    expect(p('Захист та декоративне оздоблення дерев\'яних і мінеральних поверхонь в інтер\'єрі', 'laky')).toBe("Захист та декорування поверхонь в інтер'єрі");
    expect(p('Захист та декорування деревини (фасади, вікна, Двері, садові меблі, Тераси', 'laky')).toBe('Захист та декорування деревини');
  });
  it('загальні правила працюють і без категорії', () => {
    expect(p('Захист деревини від гнилі, цвілі, синяви та комах')).toBe('Антисептичний захист деревини');
    expect(p('Склеювання деревини, шпону, фанери та деревних композитних матеріалів')).toBe('Склеювання деревини та деревних матеріалів');
    expect(p('Тонування водоемульсійних фарб, акрилових штукатурок, ґрунтовок')).toBe('Тонування фарб, лаків і ґрунтовок');
  });
  it('пластифікатори: зимові, тепла підлога, фібра, решта', () => {
    expect(p("Добавка для бетонних та розчинних сумішей при від'ємних температурах", 'plastyfikatory-dlya-betonu')).toBe('Зимове бетонування (протиморозна добавка)');
    expect(p('Пластифікатор для бетонних стяжок із системою підлогового опалення', 'plastyfikatory-dlya-betonu')).toBe('Стяжки теплої підлоги');
    expect(p('Армування бетонних і цементних сумішей, запобігання усадковим тріщинам', 'plastyfikatory-dlya-betonu')).toBe('Армування бетону (фібра)');
    expect(p('Для всіх видів бетону', 'plastyfikatory-dlya-betonu')).toBe('Пластифікація бетонних і цементних розчинів');
  });
  it('інші лейбли не чіпає', () => {
    expect(canonicalCharValue('Колір', 'Універсальний')).toBe('Універсальний');
  });
});
