const BASE = 'https://fixline.com.ua';

export function generateStaticParams() {
  return ARTICLES.map(a => ({ slug: a.slug }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const article = getArticle(slug);
  if (!article) return {};
  const title = article.titleRu ?? article.title;
  const description = article.descriptionRu ?? article.description;
  return {
    title,
    description,
    keywords: article.keywords,
    alternates: {
      canonical: `${BASE}/ru/blog/${slug}`,
      languages: {
        'uk': `${BASE}/blog/${slug}`,
        'ru': `${BASE}/ru/blog/${slug}`,
        'x-default': `${BASE}/blog/${slug}`,
      },
    },
    openGraph: {
      title,
      description,
      url: `${BASE}/ru/blog/${slug}`,
      siteName: 'FIXLINE',
      locale: 'ru_RU',
      type: 'article',
      publishedTime: article.date,
      images: [{ url: `${BASE}/blog/${slug}/opengraph-image`, width: 1200, height: 630, alt: title }],
    },
  };
}

