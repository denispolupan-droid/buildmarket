'use client';

import { useCategoryView } from '../../lib/category-view';

/**
 * Ховає серверно-відрендерений вміст після клієнтського перемикання категорії.
 *
 * Навіщо: перемикання категорій у сайдбарі — миттєвий pushState без навігації
 * (див. lib/category-view.ts). Серверні блоки, прив'язані до АДРЕСИ першого
 * завантаження — наприклад, SEO-список «Усі товари розділу» — при цьому не
 * оновлюються і показували товари попередньої категорії (баг: на
 * /shop/farby-dlya-pidlohy висів список із 75 дисків та пістолетів).
 *
 * Шапку і «Про категорію» ми оновлюємо через category-view живими даними, а
 * цей список — сотні посилань — дорого перераховувати на клієнті й ні до чого:
 * він існує для краулера, а краулер бачить лише серверний рендер. Тому після
 * першого ж клієнтського перемикання просто ховаємо його. Прямий захід і
 * перезавантаження показують коректний серверний список, як і раніше.
 */
export default function HideOnCategorySwitch({ children }: { children: React.ReactNode }) {
  const switched = useCategoryView() !== null;
  return switched ? null : <>{children}</>;
}
