export function generateStaticParams() {
  return ARTICLES.map(a => ({ slug: a.slug }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const article = getArticle(slug);
  if (!article) return {};
  return {
    title: `${article.title} | FIXLINE`,
    description: article.description,
    keywords: article.keywords,
    alternates: { canonical: `https://fixline.com.ua/blog/${slug}`, languages: { 'uk': `https://fixline.com.ua/blog/${slug}`, 'ru': `https://fixline.com.ua/blog/${slug}`, 'x-default': `https://fixline.com.ua/blog/${slug}` } },
    openGraph: {
      title: article.title,
      description: article.description,
      url: `https://fixline.com.ua/blog/${slug}`,
      siteName: 'FIXLINE',
      locale: 'uk_UA',
      type: 'article',
      publishedTime: article.date,
      images: [{ url: `https://fixline.com.ua/blog/${slug}/opengraph-image`, width: 1200, height: 630, alt: article.title }],
    },
  };
}

