-- ============================================================================
-- 071  ТТН на рівні РН (sale document) — модель «РН = посилка» (Варіант 3)
-- ============================================================================
-- Замовлення може їхати кількома посилками (часткова відгрузка): кожна посилка —
-- окрема РН зі своєю ТТН. РН створюється чернеткою при відгрузці і проводиться
-- (виручка/COGS/склад + комісія по її позиціях) саме тоді, коли ДОСТАВЛЕНА її
-- посилка. Щоб крон доставки міг знайти потрібну РН по номеру ТТН — зберігаємо
-- ТТН на самій накладній.
-- ============================================================================
ALTER TABLE acc_documents ADD COLUMN IF NOT EXISTS tracking_number text;
COMMENT ON COLUMN acc_documents.tracking_number IS
  'ТТН посилки для РН (sale): проводимо цю накладну, коли доставлено саме її посилку (Варіант 3).';
CREATE INDEX IF NOT EXISTS idx_acc_documents_tracking ON acc_documents (tracking_number) WHERE tracking_number IS NOT NULL;
