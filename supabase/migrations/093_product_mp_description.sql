-- Окремий опис товару для маркетплейсів.
--
-- Досі фіди Rozetka і Prom віддавали description_full — той самий текст, що й на
-- сайті. Два наслідки, обидва не гіпотетичні:
--   1) дубль контенту: Google склеює однакові сторінки і показує авторитетнішу,
--      тобто карточку маркетплейса, а не наш товар — по довгому хвосту запитів,
--      заради якого цей текст і писався;
--   2) хвіст «Замовити … в інтернет-магазині FIXLINE …», яким закінчується
--      кожен повний опис, Rozetka вважає згадкою стороннього ресурсу і блокує
--      поле опису (станом на 2026-08-10 — 252 позиції з 752).
--
-- Тому маркетплейси отримують власний текст: коротший, від характеристик і
-- застосування, без згадок магазину й доставки. Сайт лишається з повним описом
-- як з ексклюзивом.
alter table products add column if not exists description_mp    text;
alter table products add column if not exists description_mp_ru text;

comment on column products.description_mp is
  'Опис для фідів маркетплейсів (UA), 700-900 знаків, без згадок магазину/доставки. Порожній — фід бере description_full.';
comment on column products.description_mp_ru is
  'Те саме російською (переклад description_mp).';
