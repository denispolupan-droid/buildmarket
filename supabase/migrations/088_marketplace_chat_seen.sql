-- Власний признак прочитаності чатів маркетплейсів.
--
-- Навіщо своя таблиця, коли Rozetka віддає totalUnread: її лічильник відбиває
-- стан ЇХНЬОГО кабінету. Хтось відкрив діалог у застосунку Rozetka — лічильник
-- обнулився, а наш менеджер повідомлення так і не побачив. Плюс Prom лічильника
-- на рівні кімнати не має взагалі, тож його чати не підсвічувались ніколи.
--
-- Зберігаємо НЕ час перегляду, а мітку оновлення чату, яку ми бачили
-- (seen_update — рядок площадки «2026-08-06 09:16:39»). Тоді порівняння йде
-- «час площадки проти часу площадки», і питання часових поясів не виникає
-- взагалі: Київ узимку +2, улітку +3, і будь-яка спроба звести це до UTC
-- давала б чати, що спалахують як нові через кілька годин після перегляду.
--
-- Чат непрочитаний, поки його updated новіший за seen_update.
CREATE TABLE IF NOT EXISTS marketplace_chat_seen (
  mp          TEXT        NOT NULL CHECK (mp IN ('rozetka', 'prom')),
  chat_id     TEXT        NOT NULL,   -- rozetka: id чату · prom: room_ident
  seen_update TEXT,                   -- мітка updated чату на момент перегляду
  seen_at     TIMESTAMPTZ NOT NULL DEFAULT now(),  -- коли саме дивились (для діагностики)
  PRIMARY KEY (mp, chat_id)
);

-- Як і решта службових таблиць адмінки: доступ лише через service role.
ALTER TABLE marketplace_chat_seen ENABLE ROW LEVEL SECURITY;
