-- Фактичний постачальник відвантаження дроп-замовлення.
-- Менеджер підтверджує в картці замовлення, хто реально відправив товар;
-- recordDropshipSale відносить борг перед постачальником саме на нього,
-- а не на постачальника з мапінгу SKU (який може бути альтернативним).
alter table orders add column if not exists shipping_supplier_id integer references suppliers(id);

comment on column orders.shipping_supplier_id is
  'Фактичний постачальник, який відвантажив дроп-замовлення (обирає менеджер; використовується для віднесення боргу перед постачальником)';
