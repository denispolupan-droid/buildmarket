-- Товари статті зберігаються артикулами, а не «запеченим» HTML-блоком.
-- Раніше блок «Чим це зробити» вписувався в content_html разом із цінами й
-- наявністю — вони застигали на момент вставки, і через тиждень стаття
-- показувала неправдиві ціни. Тепер тут лише список SKU, а блок збирається
-- на рендері з поточних даних (кеш товарів — 60 с, як на вітрині).
ALTER TABLE blog_posts ADD COLUMN IF NOT EXISTS product_skus TEXT[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN blog_posts.product_skus IS
  'Артикули товарів для блоку «Чим це зробити». Порядок = порядок показу. Ціни й наявність беруться на рендері.';
