-- Пошук по телефону в журналі замовлень не знаходив нічого, якщо номер
-- набрали суцільно («068052»), а в базі він лежить із роздільниками.
-- Формати різні й залежать від джерела: «380685604115» (Rozetka),
-- «+380688757977» (Prom), «+38 (068) 052-92-36» (сайт) — на 669 замовлень
-- це 446 / 165 / 56 відповідно.
--
-- Колонка лише з цифрами знімає питання формату: і запит, і значення
-- зводяться до цифр, далі звичайний ilike '%…%'. GENERATED STORED — щоб не
-- було шансу розійтися з phone: Postgres перераховує її сам на кожен запис.
-- Індексу навмисно немає: пошук іде по підрядку (ilike '%…%'), звичайний
-- btree для нього не працює, а таблиця маленька.
ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS phone_digits TEXT
  GENERATED ALWAYS AS (regexp_replace(COALESCE(phone, ''), '\D', '', 'g')) STORED;

COMMENT ON COLUMN orders.phone_digits IS 'Телефон без роздільників — для пошуку; рахується з phone автоматично';
