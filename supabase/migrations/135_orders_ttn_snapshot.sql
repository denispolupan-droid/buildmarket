-- Що саме вписали в накладну при її створенні: післяплата, оголошена вартість,
-- вага, габарити, місця, відправник, отримувач, платник. Перевізники Rozetka
-- (власний договір і маркетплейс) цих даних назад не віддають, а НП віддає не все
-- (габарити по місцях) — тож для вікна «Деталі ЕН» зберігаємо власний знімок.
-- Знімок прив'язаний до номера (поле ttn): якщо номер потім замінили вручну,
-- старий знімок до нової накладної не показується.
alter table public.orders add column if not exists ttn_snapshot jsonb;

comment on column public.orders.ttn_snapshot is
  'Знімок даних, переданих перевізнику при створенні накладної (lib/ttn-snapshot.ts). Ключ ttn — номер, якого він стосується.';
