-- Пошук за іменем не знаходив замовлення, якщо написання різне: у базі
-- контакт лежить так, як прийшов із площадки («Стельмах Александр»), а шукають
-- як звикли («Олександр Стельмах»). Порядок слів уже полагоджено, лишається
-- орфографія: і/и/ы, є/е/э/ё, ґ/г, апостроф, м'який знак — «Лисенко» проти
-- «Лысенко», «Сергієнко» проти «Сергиенко».
--
-- Колонки зі згорнутим написанням знімають питання: і запит, і значення
-- зводяться до одного вигляду, далі звичайний ilike. GENERATED STORED — щоб не
-- розійтися з оригіналом: Postgres перераховує сам на кожен запис.
--
-- ТЕ САМЕ правило продубльоване в lib/name-search.ts (функція fold) — міняти
-- тільки разом, інакше запит і база згортатимуть по-різному.
-- translate(): перші сім символів замінюються попарно (і ї ы → и, ё э є → е,
-- ґ → г), решта ('’`-ьъ) видаляється, бо рядок заміни коротший. Порядок обох
-- рядків звіряти посимвольно: зсув на одну позицію робив із «Сысоев» «сесоев».
--
-- Імена з різними коренями (Олександр/Александр, Микола/Николай) цим не
-- лікуються — для них список коренів у lib/name-search.ts, на боці запиту.
ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS contact_norm TEXT
  GENERATED ALWAYS AS (translate(lower(COALESCE(contact, '')), 'іїыёэєґ''’`-ьъ', 'иииееег')) STORED;

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS company_norm TEXT
  GENERATED ALWAYS AS (translate(lower(COALESCE(company, '')), 'іїыёэєґ''’`-ьъ', 'иииееег')) STORED;

COMMENT ON COLUMN orders.contact_norm IS 'contact зі згорнутою орфографією (і/и/ы, є/е/э/ё, ґ/г, без ьъ та апострофів) — для пошуку; див. lib/name-search.fold';
COMMENT ON COLUMN orders.company_norm IS 'company зі згорнутою орфографією — для пошуку; див. lib/name-search.fold';
