-- gclid — ідентифікатор рекламного кліку Google.
--
-- Навіщо: щоб віддавати Google офлайн-конверсії, тобто фактичну валову
-- прибутковість кожного замовлення як цінність конверсії. Тоді ставки
-- оптимізуються на маржу, а не на кількість замовлень, і не потрібен тег на
-- сайті (його все одно блокує наш CSP).
--
-- lib/utm.ts розпізнавав gclid і раніше, але лише щоб проставити
-- utm_source=google — сам ідентифікатор викидався. Відновити його заднім числом
-- неможливо: він живе тільки в посиланні, за яким людина прийшла.
--
-- Колонка не обов'язкова і ні на що не впливає, доки нею не почнуть
-- користуватись: звичайні замовлення просто лишають NULL.

alter table orders add column if not exists gclid text;

comment on column orders.gclid is
  'Google Click ID з рекламного переходу. Потрібен для вивантаження офлайн-конверсій у Google Ads.';

-- Вивантаження шукає замовлення з gclid за період — індекс лише по заповнених.
create index if not exists idx_orders_gclid
  on orders (created_at)
  where gclid is not null;
